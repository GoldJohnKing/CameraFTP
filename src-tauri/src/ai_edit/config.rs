use serde::{Deserialize, Serialize};
use ts_rs::TS;

/// AI修图总配置
#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[ts(export)]
#[serde(rename_all = "camelCase", default)]
pub struct AiEditConfig {
    /// 接收图片后自动触发
    pub auto_edit: bool,
    /// 自动修图提示词
    pub prompt: String,
    /// 手动修图上次使用的提示词
    pub manual_prompt: String,
    /// 手动修图上次使用的模型（空则使用 provider.model）
    pub manual_model: String,
    /// Provider 配置
    pub provider: ProviderConfig,
}

impl Default for AiEditConfig {
    fn default() -> Self {
        Self {
            auto_edit: false,
            prompt: String::new(),
            manual_prompt: String::new(),
            manual_model: String::new(),
            provider: ProviderConfig::default(),
        }
    }
}

/// Provider 配置枚举（预留扩展）
#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[ts(export)]
#[serde(tag = "type", rename_all = "kebab-case")]
pub enum ProviderConfig {
    SeedEdit(SeedEditConfig),
}

impl Default for ProviderConfig {
    fn default() -> Self {
        Self::SeedEdit(SeedEditConfig::default())
    }
}

/// 火山引擎 SeedEdit 配置
#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[ts(export)]
#[serde(rename_all = "camelCase", default)]
pub struct SeedEditConfig {
    /// API Key
    pub api_key: String,
    /// 模型 ID
    pub model: String,
}

/// Seedream model catalog entry: stable model id + user-facing label.
///
/// Single source of truth for the seedream model dropdown (frontend config
/// panel, prompt dialogs, native Android dialog) and for the default model.
/// Exported to TypeScript by `src-tauri/src/bin/export-bindings.rs`
/// (`./build.sh gen-types`) as `bindings/SeedreamModels.ts` — ts-rs 10.1
/// cannot export `const` values, so the file is generated by hand there.
#[derive(Debug, serde::Serialize)]
pub struct SeedreamModelDef {
    /// Stable model id sent to the provider API
    pub value: &'static str,
    /// Display label shown in dropdowns
    pub label: &'static str,
}

/// Seedream model catalog. Order matters: the first entry is the default
/// model (see [`DEFAULT_SEEDREAM_MODEL`]).
pub const SEEDREAM_MODELS: &[SeedreamModelDef] = &[
    SeedreamModelDef {
        value: "doubao-seedream-5-0-260128",
        label: "Doubao-Seedream-5.0-lite",
    },
    SeedreamModelDef {
        value: "doubao-seedream-4-5-251128",
        label: "Doubao-Seedream-4.5",
    },
    SeedreamModelDef {
        value: "doubao-seedream-4-0-250828",
        label: "Doubao-Seedream-4.0",
    },
];

/// Default model: always the first catalog entry (single decision point —
/// changing the catalog order changes the default).
pub const DEFAULT_SEEDREAM_MODEL: &str = SEEDREAM_MODELS[0].value;

impl Default for SeedEditConfig {
    fn default() -> Self {
        Self {
            api_key: String::new(),
            model: DEFAULT_SEEDREAM_MODEL.to_string(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn seedream_catalog_default_is_first_entry() {
        assert_eq!(DEFAULT_SEEDREAM_MODEL, SEEDREAM_MODELS[0].value);
        assert!(!SEEDREAM_MODELS.is_empty());
    }

    #[test]
    fn seedream_catalog_entries_have_unique_nonempty_ids_and_labels() {
        let mut values = std::collections::HashSet::new();
        let mut labels = std::collections::HashSet::new();
        for model in SEEDREAM_MODELS {
            assert!(!model.value.is_empty(), "empty value in catalog");
            assert!(!model.label.is_empty(), "empty label in catalog");
            assert!(values.insert(model.value), "duplicate value: {}", model.value);
            assert!(labels.insert(model.label), "duplicate label: {}", model.label);
        }
    }

    #[test]
    fn seedream_catalog_serializes_to_value_label_objects() {
        let json = serde_json::to_string(SEEDREAM_MODELS).unwrap();
        assert!(json.contains("\"value\":\"doubao-seedream-5-0-260128\""));
        assert!(json.contains("\"label\":\"Doubao-Seedream-5.0-lite\""));
        let parsed: Vec<std::collections::BTreeMap<String, String>> =
            serde_json::from_str(&json).unwrap();
        assert_eq!(parsed.len(), SEEDREAM_MODELS.len());
    }

    #[test]
    fn default_config_has_auto_edit_false() {
        let config = AiEditConfig::default();
        assert!(!config.auto_edit);
    }

    #[test]
    fn default_config_has_empty_prompt() {
        let config = AiEditConfig::default();
        assert!(config.prompt.is_empty());
    }

    #[test]
    fn default_config_has_seed_edit_provider() {
        let config = AiEditConfig::default();
        assert!(matches!(config.provider, ProviderConfig::SeedEdit(_)));
    }

    #[test]
    fn config_with_custom_values() {
        let config = AiEditConfig {
            auto_edit: false,
            prompt: "enhance colors".to_string(),
            manual_prompt: "manual prompt".to_string(),
            manual_model: "doubao-seedream-4-0-250828".to_string(),
            provider: ProviderConfig::SeedEdit(SeedEditConfig {
                api_key: "sk-test-123".to_string(),
                model: DEFAULT_SEEDREAM_MODEL.to_string(),
            }),
        };
        let json = serde_json::to_string(&config).unwrap();
        let back: AiEditConfig = serde_json::from_str(&json).unwrap();

        assert!(!back.auto_edit);
        assert_eq!(back.prompt, "enhance colors");
        assert_eq!(back.manual_prompt, "manual prompt");
        assert_eq!(back.manual_model, "doubao-seedream-4-0-250828");
        let ProviderConfig::SeedEdit(ref se) = back.provider;
        assert_eq!(se.api_key, "sk-test-123");
    }
}
