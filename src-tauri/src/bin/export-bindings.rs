use camera_ftp_companion_lib::{
    ai_edit::config::{DEFAULT_SEEDREAM_MODEL, SEEDREAM_MODELS},
    ai_edit::progress::AiEditProgressEvent,
    commands::ExifInfo,
    config::{
        AdvancedConnectionConfig, AndroidImageOpenMethod, AndroidImageViewerConfig, AppConfig,
        AuthConfig, ImageOpenMethod, PreviewWindowConfig,
    },
    file_index::FileInfo,
    ftp::{ServerInfo, ServerStateSnapshot},
    color_grading::{presets::ColorGradingPreset, progress::ColorGradingEvent},
    platform::{PermissionStatus, ServerStartCheckResult, StorageInfo},
};
use ts_rs::{ExportError, TS};

fn export_type<T: TS + ?Sized + 'static>() -> Result<(), ExportError> {
    T::export_all()
}

/// Emit `bindings/SeedreamModels.ts` from the Rust seedream catalog.
///
/// ts-rs 10.1 cannot export `const` values (upstream: not planned), so this
/// hand-writes the file. Rust (`src-tauri/src/ai_edit/config.rs`) is the
/// single source of truth; `./build.sh gen-types` regenerates this file.
fn export_seedream_models() -> Result<(), ExportError> {
    // The default is defined as the first catalog entry; keep the generated
    // file honest if that invariant is ever broken.
    debug_assert_eq!(DEFAULT_SEEDREAM_MODEL, SEEDREAM_MODELS[0].value);

    let out_dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("bindings");
    std::fs::create_dir_all(&out_dir)?;

    let models_json = serde_json::to_string_pretty(SEEDREAM_MODELS)
        .map_err(std::io::Error::other)?;
    let content = format!(
        "// Code-generated by export-bindings (gen-types). DO NOT EDIT.\n\
         // CameraFTP - A Cross-platform FTP companion for camera photo transfer\n\
         // Copyright (C) 2026 GoldJohnKing <GoldJohnKing@Live.cn>\n\
         // SPDX-License-Identifier: AGPL-3.0-or-later\n\
         \n\
         export interface SeedreamModelOption {{ label: string; value: string }}\n\
         \n\
         export const SEEDREAM_MODELS: SeedreamModelOption[] = {models_json};\n\
         \n\
         export const DEFAULT_SEEDREAM_MODEL = '{DEFAULT_SEEDREAM_MODEL}';\n"
    );
    std::fs::write(out_dir.join("SeedreamModels.ts"), content)?;
    Ok(())
}

fn main() -> Result<(), ExportError> {
    export_type::<AuthConfig>()?;
    export_type::<AdvancedConnectionConfig>()?;
    export_type::<ImageOpenMethod>()?;
    export_type::<PreviewWindowConfig>()?;
    export_type::<AndroidImageOpenMethod>()?;
    export_type::<AndroidImageViewerConfig>()?;
    export_type::<AppConfig>()?;
    export_type::<ExifInfo>()?;
    export_type::<FileInfo>()?;
    export_type::<StorageInfo>()?;
    export_type::<PermissionStatus>()?;
    export_type::<ServerStartCheckResult>()?;
    export_type::<ServerStateSnapshot>()?;
    export_type::<ServerInfo>()?;
    export_type::<camera_ftp_companion_lib::ftp::types::ServerRuntimeView>()?;
    export_type::<AiEditProgressEvent>()?;
    export_type::<ColorGradingPreset>()?;
    export_type::<ColorGradingEvent>()?;

    #[cfg(target_os = "windows")]
    export_type::<camera_ftp_companion_lib::auto_open::ConfigChangedEvent>()?;

    export_seedream_models()?;

    Ok(())
}
